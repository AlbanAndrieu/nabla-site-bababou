import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import {
  chmod,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";

const canonical = [
  '/// <reference types="next" />',
  '/// <reference types="next/image-types/global" />',
  'import "./.next/types/routes.d.ts";',
  'import "./.next/types/root-params.d.ts";',
  "",
].join("\n");

async function run(cwd: string, command: string, args: string[]) {
  await new Promise<void>((resolve, reject) => {
    const child = spawn(command, args, { cwd, stdio: "ignore" });
    child.once("error", reject);
    child.once("exit", (code) =>
      code === 0 ? resolve() : reject(new Error(`${command} exited ${code}`)),
    );
  });
}

async function waitForMutation(path: string, timeoutMs = 3000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if ((await readFile(path, "utf8")) === "generated by next dev\n") return;
    await new Promise((resolve) => setTimeout(resolve, 20));
  }
  throw new Error("fake Next process did not mutate next-env.d.ts");
}

test("Next wrapper restores next-env.d.ts after Playwright-style SIGTERM", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "bababou-next-env-"));
  t.after(async () => rm(root, { recursive: true, force: true }));

  const scriptsDir = join(root, "scripts");
  const binDir = join(root, "bin");
  await mkdir(scriptsDir, { recursive: true });
  await mkdir(binDir, { recursive: true });

  const wrapper = await readFile(
    new URL("../scripts/run-next-clean.sh", import.meta.url),
    "utf8",
  );
  await writeFile(join(scriptsDir, "run-next-clean.sh"), wrapper);
  await chmod(join(scriptsDir, "run-next-clean.sh"), 0o755);
  await writeFile(join(root, "next-env.d.ts"), canonical);

  await run(root, "git", ["init", "--quiet"]);
  await run(root, "git", ["add", "next-env.d.ts"]);

  await writeFile(
    join(binDir, "npx"),
    [
      "#!/usr/bin/env bash",
      "set -euo pipefail",
      'printf "generated by next dev\\n" > next-env.d.ts',
      "trap 'exit 0' TERM INT",
      "while true; do sleep 0.05; done",
      "",
    ].join("\n"),
  );
  await chmod(join(binDir, "npx"), 0o755);

  const child = spawn("bash", ["scripts/run-next-clean.sh", "dev"], {
    cwd: root,
    env: {
      ...process.env,
      PATH: `${binDir}:${process.env.PATH ?? ""}`,
    },
    stdio: ["ignore", "pipe", "pipe"],
  });

  await waitForMutation(join(root, "next-env.d.ts"));
  child.kill("SIGTERM");

  const exit = await new Promise<{
    code: number | null;
    signal: NodeJS.Signals | null;
  }>((resolve, reject) => {
    child.once("error", reject);
    child.once("exit", (code, signal) => resolve({ code, signal }));
  });

  assert.equal(exit.signal, null);
  assert.equal(exit.code, 143);
  assert.equal(await readFile(join(root, "next-env.d.ts"), "utf8"), canonical);
});
